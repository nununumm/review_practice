public class User {

    private Long id;
    private String email;
    private String phoneNumber;
    private String deviceToken;

    public Long getId() {
        return id;
    }

    public String getEmail() {
        return email;
    }

    public String getPhoneNumber() {
        return phoneNumber;
    }

    public String getDeviceToken() {
        return deviceToken;
    }
}
