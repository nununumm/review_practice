// 通知の「送り方の強さ」を1つの列挙型（＝決まった選択肢しか持てない型）にまとめたもの。
// bad では isUrgent と isSilent という2つの boolean で表していたが、
// 「緊急なのに静かに（音を鳴らさず）送る」という矛盾した組合せを型として作れてしまっていた。
// ここでは「NORMAL / URGENT / SILENT のどれか1つだけを選ぶ」形にすることで、
// URGENT と SILENT を同時に指定することが、そもそも不可能になる（＝型で矛盾を防ぐ）。
public enum DeliveryMode {

    NORMAL,   // 通常。ふつうに送る
    URGENT,   // 緊急。高優先度で、目立つように送る
    SILENT    // 静かに。通知音を鳴らさずに送る
}
