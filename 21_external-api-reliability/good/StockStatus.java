package com.example.stock;

/**
 * 在庫確認の結果を表す状態。
 *
 * 【重要】「在庫が足りない(SHORTAGE)」と「そもそも確認できなかった(CHECK_FAILED)」は
 * まったく意味が違うので、必ず別の状態として区別する。
 * bad版はこの区別が無く、確認失敗を黙って捨てていた（＝在庫ありと誤認する事故の元）。
 *
 * ※ 第16問で学んだ「状態はマジックストリングでなくenumで表す」の実践。
 */
public enum StockStatus {
    AVAILABLE,     // 必要数を引き当てられる（在庫 >= 必要数）
    SHORTAGE,      // 在庫はあるが必要数に満たない（0個も含む）＝ 確実な情報
    CHECK_FAILED   // 確認できなかった（例外・タイムアウト・空応答など）＝ 情報が無い状態
}
